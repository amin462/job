-- Fact 1: Job Postings (grain = 1 unique posting snapshot per source + source_job_id)
-- Note: NO description/qualifications full text and NO HR contact PII stored in DW.
create table if not exists dw.fact_job_posting (
  posting_key         bigint primary key generated by default as identity,
  source_key          smallint not null references dw.dim_source (source_key),
  source_job_id       text not null,
  source_url          text not null,
  title_short         text,                  -- Normalized short title only (never full description/qualifications)
  date_posted_key     int references dw.dim_date (date_key),
  valid_through_key   int references dw.dim_date (date_key),
  location_key        int references dw.dim_location (location_key),
  company_key         bigint references dw.dim_company (company_key),
  occupation_key      int references dw.dim_occupation (occupation_key),
  education_key       smallint references dw.dim_education (education_key),
  experience_key      smallint references dw.dim_experience (experience_key),
  employment_type_key smallint references dw.dim_employment_type (employment_type_key),
  salary_min          numeric,
  salary_max          numeric,
  salary_mid          numeric,               -- NULL = negotiable / undisclosed / out of [5000, 500000]
  salary_open_max     boolean not null default false, -- true when posting specifies minimum only ("15,000 ขึ้นไป")
  salary_unit_orig    text,                  -- 'MONTH' | 'DAY' | 'HOUR'
  has_salary          boolean generated always as (salary_mid is not null) stored,
  n_skills            smallint not null default 0,
  first_seen_date_key int references dw.dim_date (date_key),
  last_seen_date_key  int references dw.dim_date (date_key),
  sample_stratum      text,                  -- Stratified sampling cell e.g. 'p=10|c=บัญชี'
  sample_weight       numeric not null default 1 check (sample_weight > 0), -- N_h / n_h
  scrape_run_id       bigint,
  unique (source_key, source_job_id),
  check (salary_min is null or salary_max is null or salary_min <= salary_max)
);

-- Fact 2: Posting x Skill Bridge (grain = 1 posting x 1 canonical skill)
create table if not exists dw.fact_posting_skill (
  posting_key    bigint not null references dw.fact_job_posting (posting_key) on delete cascade,
  skill_key      int not null references dw.dim_skill (skill_key),
  match_alias_id bigint references dw.skill_alias (alias_id) on delete set null,
  primary key (posting_key, skill_key)
);

-- Fact 3: National Monthly Labor Context Metrics (T3.9, optional macro context cards)
create table if not exists dw.fact_labor_monthly (
  date_key int not null references dw.dim_date (date_key),
  metric   text not null,
  value    numeric,
  source   text,
  unit     text,
  primary key (date_key, metric)
);

-- Performance indexes for DW & Mart queries
create index if not exists idx_fact_job_posting_location    on dw.fact_job_posting (location_key);
create index if not exists idx_fact_job_posting_occupation  on dw.fact_job_posting (occupation_key);
create index if not exists idx_fact_job_posting_date_posted on dw.fact_job_posting (date_posted_key);
create index if not exists idx_fact_job_posting_first_seen  on dw.fact_job_posting (first_seen_date_key);
create index if not exists idx_fact_job_posting_last_seen   on dw.fact_job_posting (last_seen_date_key);
create index if not exists idx_fact_job_posting_company     on dw.fact_job_posting (company_key);
create index if not exists idx_fact_job_posting_has_salary  on dw.fact_job_posting (occupation_key, location_key) where has_salary;
create index if not exists idx_fact_posting_skill_skill     on dw.fact_posting_skill (skill_key);
