-- 1. Dimension Tables

create table if not exists dw.dim_date (
  date_key    int primary key,              -- yyyymmdd
  full_date   date not null unique,
  year        int not null,
  quarter     int not null,
  month       int not null,
  week        int not null,                 -- ISO week number
  day_of_week int not null,                 -- 1=Mon .. 7=Sun (isodow)
  is_weekend  boolean not null
);

create table if not exists dw.dim_source (
  source_key  smallint primary key generated by default as identity,
  source_name text unique not null check (source_name in ('jobthai', 'jobbkk')),
  base_url    text,
  tos_note    text
);

create table if not exists dw.dim_location (
  location_key  int primary key generated by default as identity,
  province_code text,
  province_th   text not null,
  province_en   text,
  district_th   text not null default '',
  region        text not null check (region in ('เหนือ', 'อีสาน', 'กลาง', 'ตะวันออก', 'ตะวันตก', 'ใต้', 'ไม่ระบุ')),
  is_south14    boolean not null default false,
  unique (province_th, district_th)
);

create index if not exists idx_dim_location_province on dw.dim_location (province_th);
create index if not exists idx_dim_location_region on dw.dim_location (region);

create table if not exists dw.dim_company (
  company_key       bigint primary key generated by default as identity,
  company_name_norm text unique not null,   -- Used strictly as group in GroupKFold, never a model feature
  industry          text,
  size_band         text
);

create table if not exists dw.dim_occupation (
  occupation_key     int primary key generated by default as identity,
  occupation_cluster text not null,         -- e.g. 'Data & Analytics', 'Accounting & Finance'
  occupation_slug    text,                  -- URL slug for /occupations/[slug]
  occupation_name_th text,
  job_title_norm     text not null,
  onet_ref           text,
  unique (occupation_cluster, job_title_norm)
);

create index if not exists idx_dim_occupation_cluster on dw.dim_occupation (occupation_cluster);

create table if not exists dw.dim_skill (
  skill_key       int primary key generated by default as identity,
  skill_canonical text unique not null,     -- e.g. 'Microsoft Excel'
  skill_slug      text unique,              -- e.g. 'microsoft-excel'
  skill_name_th   text,
  skill_type      text check (skill_type in ('tool', 'technical', 'soft', 'language', 'licence')),
  skill_group     text,
  onet_ref        text,
  esco_ref        text
);

create table if not exists dw.skill_alias (
  alias_id   bigint primary key generated by default as identity,
  skill_key  int references dw.dim_skill (skill_key) on delete cascade,
  alias      text not null,
  lang       text,
  match_type text not null default 'exact' check (match_type in ('exact', 'regex', 'token', 'word_boundary')),
  status     text not null default 'approved' check (status in ('approved', 'pending', 'rejected')),
  unique (alias)
);

create index if not exists idx_skill_alias_trgm on dw.skill_alias using gin (alias gin_trgm_ops);
create index if not exists idx_skill_alias_skill_key on dw.skill_alias (skill_key);

create table if not exists dw.dim_education (
  education_key smallint primary key generated by default as identity,
  level_th      text unique not null,
  level_rank    smallint not null
);

create table if not exists dw.dim_experience (
  experience_key smallint primary key generated by default as identity,
  band_th        text unique not null,
  min_years      numeric,
  max_years      numeric
);

create table if not exists dw.dim_employment_type (
  employment_type_key smallint primary key generated by default as identity,
  type_th             text unique not null
);

