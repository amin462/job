-- 6. Seed dw.dim_date (2025-01-01 through 2027-12-31)
insert into dw.dim_date (date_key, full_date, year, quarter, month, week, day_of_week, is_weekend)
select
  to_char(d, 'YYYYMMDD')::int as date_key,
  d::date as full_date,
  extract(year from d)::int as year,
  extract(quarter from d)::int as quarter,
  extract(month from d)::int as month,
  extract(week from d)::int as week,
  extract(isodow from d)::int as day_of_week,
  extract(isodow from d) in (6, 7) as is_weekend
from generate_series(date '2025-01-01', date '2027-12-31', interval '1 day') as gs(d)
on conflict (date_key) do nothing;

